//! The resolved system theme as one immutable JSON file
//! (`$XDG_RUNTIME_DIR/nyx/theme/system.json`) with a generation number. Clients
//! that can't resolve themes themselves (the QML module) read it; nobody parses
//! theme files twice. It is replaced atomically, so a reader sees one complete
//! generation or the one before, never half of each.

use crate::resolver::Resolved;
use crate::schema::{Appearance, Origin, SCHEMA_VERSION};
use crate::tokens::Tokens;
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::io::Write;

/// The snapshot format's own version.
pub const SNAPSHOT_FORMAT: u32 = 1;

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct SnapshotTheme {
    pub id: String,
    pub name: String,
    pub appearance: Appearance,
    pub origin: Origin,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Snapshot {
    pub format: u32,
    pub schema: u32,
    pub generation: u64,
    pub scope: String,
    pub reason: String,
    pub theme: SnapshotTheme,
    pub tokens: Tokens,
    /// The established names (`bg`, `dim_text`, `on_accent`, …) for older clients.
    pub legacy: BTreeMap<String, String>,
    pub swatches: BTreeMap<String, String>,
    pub accents: BTreeMap<String, String>,
    pub issues: Vec<String>,
}

impl Snapshot {
    pub fn from_resolved(r: &Resolved, generation: u64, reason: &str) -> Snapshot {
        let p = &r.theme.palette;
        let l = &r.theme.look;
        let mut legacy: BTreeMap<String, String> =
            crate::tokens::LEGACY.iter().map(|(name, token)| (name.to_string(), r.tokens.color(token).to_string())).collect();
        legacy.insert("on_accent".into(), r.tokens.color("text.onAccent").to_string());
        legacy.insert("light".into(), p.light.to_string());
        Snapshot {
            format: SNAPSHOT_FORMAT,
            schema: SCHEMA_VERSION,
            generation,
            scope: r.scope.clone(),
            reason: reason.into(),
            theme: SnapshotTheme { id: r.meta.id.clone(), name: r.meta.name.clone(), appearance: r.meta.appearance, origin: r.meta.origin },
            tokens: r.tokens.clone(),
            legacy,
            swatches: l.swatches.iter().cloned().collect(),
            accents: l.accents.clone(),
            issues: r.issues.iter().map(ToString::to_string).collect(),
        }
    }

    /// The same theme, whatever the generation and reason.
    pub fn same_content(&self, other: &Snapshot) -> bool {
        self.theme == other.theme
            && self.tokens == other.tokens
            && self.legacy == other.legacy
            && self.swatches == other.swatches
            && self.accents == other.accents
    }
}

/// The default theme's snapshot as the QML module's `fallback.js`, used until a
/// real snapshot is readable. Generated: `nyx-theme qml-fallback`.
pub fn fallback_js() -> String {
    let reg = crate::Registry::builtin();
    let r = crate::resolver::resolve_id(&reg, crate::DEFAULT_THEME, None, &crate::A11y::default()).expect("the default theme is built in");
    let mut s = Snapshot::from_resolved(&r, 0, "fallback");
    s.scope = "system".into();
    s.issues.clear();
    format!(
        ".pragma library\n// Generated by `nyx-theme qml-fallback` from the built-in {} theme; don't edit.\n\nvar snapshot = {};\n",
        r.meta.name,
        serde_json::to_string_pretty(&s).unwrap_or_default()
    )
}

/// The current snapshot, if one has been written.
pub fn read() -> Option<Snapshot> {
    serde_json::from_str(&std::fs::read_to_string(crate::paths::snapshot_file()).ok()?).ok()
}

/// The newest generation announced so far.
pub fn generation() -> u64 {
    std::fs::read_to_string(crate::paths::runtime_dir().join("generation"))
        .ok()
        .and_then(|s| s.trim().parse().ok())
        .or_else(|| read().map(|s| s.generation))
        .unwrap_or(0)
}

/// What [`publish`] did.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Published {
    pub generation: u64,
    /// A new generation was written (and should be announced).
    pub changed: bool,
}

fn write_atomic(path: &std::path::Path, bytes: &[u8]) -> std::io::Result<()> {
    let dir = path.parent().ok_or_else(|| std::io::Error::other("no parent"))?;
    std::fs::create_dir_all(dir)?;
    let tmp = dir.join(format!(".{}.{}", path.file_name().unwrap_or_default().to_string_lossy(), std::process::id()));
    let mut f = std::fs::File::create(&tmp)?;
    f.write_all(bytes)?;
    f.sync_all()?;
    std::fs::rename(&tmp, path)
}

/// Write `r` as the next generation, unless it is the theme already published and
/// `force` is off. Writers take a lock, so two never hand out the same generation.
pub fn publish(r: &Resolved, reason: &str, force: bool) -> std::io::Result<Published> {
    let dir = crate::paths::runtime_dir();
    std::fs::create_dir_all(&dir)?;
    let lock = std::fs::OpenOptions::new().create(true).truncate(false).write(true).open(dir.join(".lock"))?;
    lock.lock()?;
    let current = generation();
    let mut next = Snapshot::from_resolved(r, current, reason);
    if !force && read().is_some_and(|old| old.same_content(&next)) {
        return Ok(Published { generation: current, changed: false });
    }
    next.generation = current + 1;
    let json = serde_json::to_vec_pretty(&next).map_err(std::io::Error::other)?;
    write_atomic(&crate::paths::snapshot_file(), &json)?;
    write_atomic(&dir.join("generation"), next.generation.to_string().as_bytes())?;
    Ok(Published { generation: next.generation, changed: true })
}
