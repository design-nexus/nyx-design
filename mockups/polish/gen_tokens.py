#!/usr/bin/env python3
"""Write tokens.css from the shipped Nyx Dark and Nyx Light themes."""
import pathlib
import tomllib

here = pathlib.Path(__file__).resolve().parent
themes = here.parent.parent / "crates" / "nyx-theme" / "themes"

CORE = ["bg", "panel", "card", "raised", "surface", "popover", "text", "dim_text",
        "text_tertiary", "accent", "border", "divider", "muted", "danger", "warning",
        "success", "shadow"]


def block(name: str, selector: str) -> str:
    t = tomllib.loads((themes / f"{name}.toml").read_text())
    lines = [f"{selector} {{", f"  color-scheme: {'light' if t['light'] else 'dark'};"]
    for key in CORE:
        name = "theme-accent" if key == "accent" else key.replace("_", "-")
        lines.append(f"  --{name}: {t[key]};")
    lines.append(f"  --hover: {round(t['hover'] * 100)}%;")
    lines.append(f"  --selection: {round(t['selection'] * 100)}%;")
    lines.append(f"  --on-accent: {'#ffffff' if t['light'] else t['bg']};")
    for key, value in t["swatches"].items():
        lines.append(f"  --sw-{key}: {value};")
    for section, swatch in t["sections"]["settings"].items():
        lines.append(f"  --sec-{section}: var(--sw-{swatch});")
    shape = t["shape"]
    lines.append(f"  --r-small: {shape['radius_small']}px;")
    lines.append(f"  --r-card: {shape['radius_card']}px;")
    lines.append(f"  --r-dialog: {shape['radius_dialog']}px;")
    lines.append("}")
    return "\n".join(lines)


out = "/* Generated by gen_tokens.py from crates/nyx-theme/themes. */\n\n"
out += block("nyx-dark", ':root, [data-theme="dark"]') + "\n\n"
out += block("nyx-light", '[data-theme="light"]') + "\n\n"
out += """/* Derived, as nyx-theme derives them for GTK. */
:root, [data-theme] {
  --accent: var(--app-accent, var(--theme-accent));
  --nav-active: color-mix(in srgb, var(--accent) var(--selection), var(--bg));
  --row-hover: color-mix(in srgb, var(--accent) var(--hover), var(--bg));
  --field: color-mix(in srgb, var(--text) 3.5%, transparent);
  --track: color-mix(in srgb, var(--text) 10%, transparent);
  --veil: color-mix(in srgb, color-mix(in srgb, var(--bg) 55%, var(--shadow)) 82%, transparent);
}
"""
(here / "tokens.css").write_text(out)
print("wrote", here / "tokens.css")
