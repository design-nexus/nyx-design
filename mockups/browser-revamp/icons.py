#!/usr/bin/env python3
"""Writes icons.js: Umbra's symbolic glyphs (umbra-icons/umbra/symbolic_src.py) by the names the
mockups use, and Browser's own icons (nyx-browser/src/nyx/icons) for what Umbra doesn't draw."""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROJECTS = HERE.parents[2]
sys.path.insert(0, str(PROJECTS / "umbra-icons"))
from umbra.symbolic_src import path  # noqa: E402

# Mockup name -> Umbra glyph.
UMBRA = {
    "arrow-right": "arrow-right", "back": "arrow-left", "forward": "arrow-right", "chevron": "pan-down",
    "bookmark": "bookmark", "browser": "app", "check": "check", "close": "close", "plus": "plus", "minus": "minus",
    "cloud": "cloud", "code": "code", "computer": "computer", "copy": "copy", "download": "download",
    "eye": "reveal", "folder": "folder", "folder-open": "folder-open", "font": "font", "globe": "globe",
    "grid": "grid", "grip": "drag", "history": "recent", "clock": "recent", "home": "home", "image": "image",
    "key": "key", "link": "link", "lock": "lock", "mail": "mail", "menu": "hamburger", "message": "chat",
    "moon": "moon", "sun": "sun", "more": "more-h", "music": "music", "picker": "eyedropper", "pin": "pin",
    "private": "private", "puzzle": "puzzle", "reload": "refresh", "search": "search", "settings": "gear",
    "share": "share", "shield": "shield", "sidebar": "sidebar", "sound": "vol-high", "volume": "vol-high",
    "star": "star", "undo": "undo", "warning": "warning", "phone": "phone", "note": "edit",
    "sliders": "sliders", "printer": "printer", "trash": "trash", "window": "win-max", "reader": "ebook",
    "user": "avatar", "bell": "bell", "camera": "camera", "mic": "mic", "location": "location",
    "expand": "fullscreen", "sync": "sync", "help": "help", "power": "power", "palette": "palette",
    "tag": "tag", "list": "list", "keyboard": "keyboard", "cert": "certificate", "file": "page",
    "zoom": "zoom-in", "video": "film", "pause": "pause", "layout": "dashboard",
}

icons = {}
for svg in sorted((PROJECTS / "nyx-browser/src/nyx/icons").glob("*.svg")):
    inner = re.search(r"<svg[^>]*>(.*)</svg>", svg.read_text(), re.S).group(1)
    icons[svg.stem] = re.sub(r"\s+", " ", inner).strip()
for name, glyph in UMBRA.items():
    icons[name] = f'<path d="{path(glyph)}"/>'

lines = [f"{json.dumps(k)}: {json.dumps(v)}," for k, v in sorted(icons.items())]
(HERE / "icons.js").write_text(
    "// Generated by icons.py: Umbra's symbolic glyphs, and Browser's own icons where Umbra has none.\n"
    "const ICONS = {\n" + "\n".join(lines) + "\n};\n"
)
print(f"{len(UMBRA)} from Umbra, {len(icons) - len(UMBRA)} from Browser")
